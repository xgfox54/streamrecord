'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const path = require('node:path');
const file = path.resolve(__dirname, '../src/components/meeting-ko/transcript-review.ts');
const moduleBox = {exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:moduleBox.exports,module:moduleBox});
const {repeatedPassages} = moduleBox.exports;
const row = (sequence_id,audio_start_time,text='기술개발과 기반시설 구축의 속도를 내야 합니다.') => ({sequence_id,audio_start_time,text,is_partial:false});
const original = [row(84,565),row(85,573)];
const before = JSON.stringify(original);
assert.deepEqual([...repeatedPassages(original)], [1]);
assert.equal(JSON.stringify(original),before,'Original text, timing and IDs stay untouched');
assert.equal(original.length,2,'Distinct utterances are never deleted');
assert.equal(repeatedPassages([row(1,0,'네.'),row(2,2,'네.')]).size,0);
assert.equal(repeatedPassages([row(1,0),row(2,60)]).size,0);
assert.equal(repeatedPassages([row(1,0),{...row(2,8),is_partial:true}]).size,0);
assert.equal(repeatedPassages([{text:original[0].text},{text:original[0].text}]).size,0);
assert.equal(repeatedPassages([row(1,0),row(2,8,'다른 회의 발언을 기록합니다.')]).size,0);
console.log('PASS: 7 review hint cases; original transcripts preserved');
